const { chromium } = require('./qa-home-guard.cjs')(require('C:/Users/Sushant/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright'));
const fs = require('fs');
const path = require('path');
const { pathToFileURL } = require('url');
const root = path.resolve(__dirname, '..');
(async () => {
  const browser = await chromium.launch({ headless: true, channel: 'chrome' });
  const page = await browser.newPage({ viewport: { width: 1280, height: 900 } });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  const checks = [];
  function check(name, value) { checks.push({ name, passed: !!value }); if (!value) throw new Error(name); }
  try {
    await page.goto(pathToFileURL(path.join(root, process.argv[2] || 'index.source-rig.html')).href);
    await page.waitForFunction(() => document.querySelector('#native-armL')?.hasAttribute('transform'));
    check('eleven timeline tracks', await page.locator('[data-rail]').count() >= 11)/*more rails were added later*/;
    check('visible native source paths', await page.locator('#actor path').count() > 20);
    check('unique SVG ids', await page.evaluate(() => { const ids = [...document.querySelectorAll('[id]')].map(x=>x.id); return ids.length === new Set(ids).size; }));
    check('clip references resolve', await page.evaluate(() => [...document.querySelectorAll('#actor [clip-path]')].every(n => document.getElementById(n.getAttribute('clip-path').match(/#([^)]*)/)[1]))));
    await page.locator('#stage').screenshot({ path: path.join(root, 'qa/source-rig-neutral.png') });
    check('native neutral expression renders', await page.locator('#native-face path').count() > 2);
    const neutral = await page.locator('#native-face').innerHTML();
    await page.locator('#native-expression-next').click();
    check('source Happy expression renders', await page.locator('#native-expression-label').textContent() === '01 Happy');
    check('expression geometry changes', await page.locator('#native-face').innerHTML() !== neutral);
    await page.locator('#stage').screenshot({ path: path.join(root, 'qa/source-rig-happy.png') });
    await page.locator('#native-expression-prev').click();
    await page.locator('[data-native-gaze="1"]').click();
    check('source Left gaze changes geometry', await page.locator('#native-face').innerHTML() !== neutral);
    await page.locator('#stage').screenshot({ path: path.join(root, 'qa/source-rig-gaze-left.png') });
    await page.locator('[data-native-gaze="0"]').click();
    await page.locator('[data-rail="mouth"]').click();
    await page.locator('#tVal').fill('2');
    await page.locator('#tVal').dispatchEvent('input');
    check('native AI speech drawing replaces expression mouth', await page.locator('#native-face').innerHTML() !== neutral);
    await page.locator('#stage').screenshot({ path: path.join(root, 'qa/source-rig-speech-ai.png') });
    await page.locator('#tVal').fill('0');
    await page.locator('#tVal').dispatchEvent('input');
    check('speech OFF restores expression mouth', await page.locator('#native-face').innerHTML() === neutral);
    const before = await page.locator('#native-armL').getAttribute('transform');
    await page.locator('[data-rail="armL"]').click();
    await page.locator('#tVal').focus();
    await page.keyboard.press('ArrowRight');
    await page.waitForFunction(before => document.querySelector('#native-armL').getAttribute('transform') !== before, before);
    check('left arm pose creates key', await page.locator('[data-track="armL"] .kf').count() === 1);
    await page.locator('#undo').click();
    check('keyboard slider Undo removes key', await page.locator('[data-track="armL"] .kf').count() === 0);
    await page.locator('#tVal').focus();
    await page.keyboard.press('ArrowRight');
    await page.reload();
    await page.waitForFunction(before => document.querySelector('#native-armL')?.getAttribute('transform') !== before, before);
    check('left arm key survives reload', await page.locator('[data-track="armL"] .kf').count() === 1);
    await page.locator('[data-rail="armR"]').click();
    await page.locator('#tVal').fill('-25');
    await page.locator('#tVal').dispatchEvent('input');
    await page.locator('[data-rail="legL"]').click();
    await page.locator('#tVal').fill('10');
    await page.locator('#tVal').dispatchEvent('input');
    await page.locator('#stage').screenshot({ path: path.join(root, 'qa/source-rig-posed.png') });
    await page.locator('[data-rail-clip="blank"]').click();
    await page.waitForFunction(() => +document.querySelector('#actor').style.opacity === 0);
    check('Blank hides source actor', true);
    await page.locator('#undo').click();
    await page.waitForFunction(() => +document.querySelector('#actor').style.opacity === 1);
    check('Undo restores actor after Blank', true);
    await page.locator('#play').click();
    await page.waitForFunction(() => document.querySelector('#play').textContent === 'Pause');
    await page.locator('#play').click();
    check('play/pause works', (await page.locator('#play').textContent()) === 'Play');
    await page.setViewportSize({ width: 390, height: 844 });
    await page.screenshot({ path: path.join(root, 'qa/source-rig-phone.png'), fullPage: true });
    check('phone viewport has no page horizontal overflow', await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
    check('no JavaScript errors', errors.length === 0);
  } finally {
    fs.writeFileSync(path.join(root, 'qa/source-art-browser-checks.json'), JSON.stringify({ checks, errors, limitations: ['Not tested on Android device', 'No native Moho visual comparison', 'No 360 or facial animation claimed'] }, null, 2));
    await browser.close();
  }
  console.log(JSON.stringify(checks));
})().catch(error => { console.error(error); process.exitCode = 1; });

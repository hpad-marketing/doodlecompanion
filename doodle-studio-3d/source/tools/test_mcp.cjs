const { chromium } = require('playwright');
const path = require('path');
(async () => {
  let page;
  const api = { 'render-status': async () => ({ state: 'idle' }), save: async ({ project }) => ({ path: '/tmp/x/' + project.name + '.ds3d.json' }), render: async r => ({ message: 'queued ' + r.name + ' frames=' + r.shot.frames.length }), settings: async () => ({}) };
  const mcp = require('../host/mcp.cjs')({ call: js => page.evaluate(`Promise.resolve(${js})`), api });
  await require('../host/server.cjs')({ root: path.join(__dirname, '..', 'app'), port: 54191, api, mcp });
  const b = await chromium.launch({ args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
  page = await b.newPage({ viewport: { width: 1600, height: 950 } });
  page.on('pageerror', e => console.log('pageerror', e.message));
  await page.goto('http://127.0.0.1:54191/');
  await page.waitForSelector('body[data-ready="1"]');
  let id = 0;
  const rpc = async (method, params) => (await (await fetch('http://127.0.0.1:54191/mcp', { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify({ jsonrpc: '2.0', id: ++id, method, params }) })).json());
  const tool = async (name, args) => { const r = await rpc('tools/call', { name, arguments: args }); return r.result.isError ? 'ERROR ' + r.result.content[0].text : JSON.parse(r.result.content[0].text); };
  console.log((await rpc('initialize', { protocolVersion: '2025-06-18' })).result.serverInfo);
  console.log('tools', (await rpc('tools/list')).result.tools.map(t => t.name).join(','));
  const lc = await tool('list_controls', {});
  console.log('controls', lc.controls.length, lc.expressions.length, lc.controls.find(c => c.id === 'armL'));
  let s = await tool('set_values', { values: { armL: 999, headYaw: 20, 'cam.lens': 24 }, frame: 0, key: true });
  console.log('clamped armL', s.values.armL, 'lens', s.values['cam.lens'], 'keys', Object.keys(s.keyed).join(','));
  s = await tool('set_values', { values: { armL: 10 }, frame: 60, key: true });
  await tool('set_ease', { id: 'armL', frame: 0, ease: 'linear' });
  s = await tool('goto', { frame: 30 });
  console.log('armL at 30 (linear 145->10):', s.values.armL);
  console.log('bad tool:', await tool('set_ease', { id: 'nope', frame: 3, ease: 'linear' }));
  console.log(await tool('set_shot', { name: 'MCP test', length: 90 }).then(s => [s.name, s.length]));
  console.log(await tool('render', { preview: true }));
  console.log(await tool('save', {}));
  console.log(await tool('render_status', {}));
  await page.screenshot({ path: 'mcp_test.png' });
  await b.close(); process.exit(0);
})();

// Assemble resources/app for Doodle Studio 3D: node tools/package.cjs OUT_DIR
const fs = require('fs'), path = require('path');
const here = path.join(__dirname, '..'), out = path.resolve(process.argv[2] || path.join(here, 'build', 'app'));
fs.rmSync(out, { recursive: true, force: true });
const copy = (from, to) => fs.cpSync(path.join(here, from), path.join(out, to), { recursive: true, filter: s => !/__pycache__|\.pyc$/.test(s) });
for (const f of ['package.json', 'main.cjs', 'preload.cjs', 'updater.cjs', 'server.cjs', 'mcp.cjs', 'render.cjs', 'library.cjs', 'spherical.cjs', 'models.cjs', 'mirror.cjs', 'looks.cjs']) copy('host/' + f, f);
copy('host/blender/Bunny3D_v2.blend', 'blender/Bunny3D_v2.blend');
for (const c of ['koala', 'frog']) copy(`host/blender/chars/${c}.blend`, `blender/chars/${c}.blend`);
copy('host/blender/addons/doodle_library', 'blender/addons/doodle_library');
copy('host/blender/addons/doodle_looks', 'blender/addons/doodle_looks');
for (const f of ['ds_bridge.py', 'ds_concat.py', 'stage.py', 'preview_export.py', 'mirror.py']) copy('host/blender/' + f, 'blender/' + f);
for (const f of fs.readdirSync(path.join(here, 'host/blender/lib')).filter(f => f.endsWith('.py') || f === 'palettes.json')) copy('host/blender/lib/' + f, 'blender/lib/' + f);
copy('app/index.html', 'ui/index.html');
copy('app/src', 'ui/src');
copy('app/vendor', 'ui/vendor');
copy('app/bunny3d.json', 'ui/bunny3d.json');
for (const f of fs.readdirSync(path.join(__dirname, '..', 'app', 'fonts'))) copy(`app/fonts/${f}`, `ui/fonts/${f}`);
copy('app/guide.md', 'ui/guide.md');
for (const c of ['koala', 'frog']) copy(`app/chars/${c}.json`, `ui/chars/${c}.json`);
for (const c of ['bunny', 'koala', 'frog']) copy(`app/chars/${c}.png`, `ui/chars/${c}.png`);
if (fs.existsSync(path.join(here, 'app/icon.png'))) copy('app/icon.png', 'ui/icon.png');
const files = [];
const walk = d => { for (const n of fs.readdirSync(d)) { const p = path.join(d, n); fs.statSync(p).isDirectory() ? walk(p) : files.push(path.relative(out, p)); } };
walk(out);
console.log(out, files.length, 'files');
